"""Generate the configuration inventory from settings.py (audit P1.3).

Introspects the ``Settings`` model — the single source of truth — and emits a markdown table
of every environment variable: canonical name, default, effect, and surface (which settings
block owns it). The default is READ from the model, and the effect is READ from the field's
source comment (or its pydantic ``description``), so this cannot drift from the code the way a
hand-maintained table would. Run ``python scripts/config_inventory.py`` to print it, or
``> docs/configuration.md`` to refresh the committed inventory.

Secrets are never rendered: any ``SecretStr`` field shows ``(secret)``, never its value.

The env-var NAME is the canonical nested form ``TESSERA_<BLOCK>__<FIELD>`` (the composite's
``env_nested_delimiter='__'``, keyed on the *composite field name*). Note the trap this script
also documents at the source: each nested block ALSO carries its own ``env_prefix`` (e.g.
``TESSERA_OBS_`` for the ``observability`` block), so a second, easy-to-confuse form exists —
and ``TESSERA_OBS__X`` (abbreviated prefix + double underscore) matches NEITHER and is silently
ignored.
"""

from __future__ import annotations

import ast
from pathlib import Path
from typing import TYPE_CHECKING

from pydantic import SecretStr
from pydantic_settings import BaseSettings

from tessera.settings import Settings

if TYPE_CHECKING:
    from pydantic.fields import FieldInfo

_SETTINGS_SRC = Path(__file__).resolve().parent.parent / "src" / "tessera" / "settings.py"
_REPO_ROOT = Path(__file__).resolve().parent.parent
_MAX_CELL = 60  # truncate long default cells so the table stays readable


def _leading_comments() -> dict[tuple[str, str], str]:
    """Map ``(ClassName, field)`` → the contiguous ``#`` comment above the field's declaration."""
    src = _SETTINGS_SRC.read_text(encoding="utf-8")
    lines = src.splitlines()
    out: dict[tuple[str, str], str] = {}
    for node in ast.walk(ast.parse(src)):
        if not isinstance(node, ast.ClassDef):
            continue
        for stmt in node.body:
            if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
                continue
            collected: list[str] = []
            idx = stmt.lineno - 2
            while idx >= 0 and lines[idx].strip().startswith("#"):
                collected.insert(0, lines[idx].strip().lstrip("#").strip())
                idx -= 1
            if collected:
                out[(node.name, stmt.target.id)] = " ".join(collected)
    return out


def _render_default(field: FieldInfo, value: object) -> str:
    """A safe, readable default cell — NEVER a secret value."""
    annotation = field.annotation
    if annotation is SecretStr or (isinstance(value, SecretStr)):
        return "`(secret)`"
    if value is None:
        return "`(unset)`"
    if hasattr(value, "value"):  # StrEnum
        return f"`{value.value}`"
    if value == "":
        return "`(empty)`"
    text = str(value).replace(str(_REPO_ROOT), "<repo>")
    return f"`{text}`" if len(text) <= _MAX_CELL else f"`{text[: _MAX_CELL - 3]}…`"


def _effect(
    comments: dict[tuple[str, str], str], cls: str, field_name: str, field: FieldInfo
) -> str:
    comment = comments.get((cls, field_name))
    if comment:
        return comment.replace("|", "\\|")
    if field.description:
        return field.description.replace("\n", " ").replace("|", "\\|")
    return "—"


def _rows() -> list[tuple[str, str, str, str]]:
    comments = _leading_comments()
    rows: list[tuple[str, str, str, str]] = []
    for block_name, block_field in Settings.model_fields.items():
        annotation = block_field.annotation
        is_block = isinstance(annotation, type) and issubclass(annotation, BaseSettings)
        if not is_block:
            env = f"TESSERA_{block_name.upper()}"
            rows.append(
                (
                    env,
                    _render_default(block_field, block_field.default),
                    _effect(comments, "Settings", block_name, block_field),
                    "top-level",
                )
            )
            continue
        nested = annotation()  # defaults only — reads no live env beyond what is unset
        for fname, finfo in annotation.model_fields.items():
            env = f"TESSERA_{block_name.upper()}__{fname.upper()}"
            rows.append(
                (
                    env,
                    _render_default(finfo, getattr(nested, fname)),
                    _effect(comments, annotation.__name__, fname, finfo),
                    annotation.__name__,
                )
            )
    return rows


def main() -> int:
    """Print the markdown inventory to stdout."""
    rows = _rows()
    print("# Configuration inventory\n")
    print("<!-- GENERATED by scripts/config_inventory.py — do not edit by hand. -->")
    print("<!-- Refresh: `uv run python scripts/config_inventory.py > docs/configuration.md` -->\n")
    print(f"{len(rows)} environment variables, read from `src/tessera/settings.py`.\n")
    print(
        "**Naming.** The canonical form is `TESSERA_<BLOCK>__<FIELD>` (double-underscore nested "
        "delimiter, keyed on the *composite field name*). Each nested block ALSO has its own "
        "`env_prefix` (a legacy second path). The trap: `observability` is exposed as "
        "`TESSERA_OBSERVABILITY__X` (canonical) or `TESSERA_OBS_X` (its block prefix) — but "
        "`TESSERA_OBS__X` (abbreviated prefix + `__`) matches neither and is silently ignored.\n"
    )
    print("| Variable | Default | Effect | Surface |")
    print("|---|---|---|---|")
    for env, default, effect, surface in rows:
        print(f"| `{env}` | {default} | {effect} | {surface} |")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
