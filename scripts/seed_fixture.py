"""Derive the e2e seed fixture's manifest from the fixture itself.

The fixture (``fixtures/e2e/pgvector-seed.sql.gz``) is a plain ``pg_dump`` of a
throwaway database seeded by the ordinary ingestion scripts — corpus JSON in,
chunks embedded by the **local** model, rows out. ``make seed-fixture`` produces
it; CI restores it into its own Postgres and never computes an embedding, so it
needs no model and no secret.

A committed binary is only as trustworthy as the guard that notices it went
stale. This module writes the manifest **from the dump**, never from a hand-typed
number: the row count is counted out of the ``COPY`` block, the vector width is
read off the DDL, and the corpus hash is recomputed from the JSON sources the
dump was built from. ``tests/unit/test_seed_fixture.py`` then re-derives all
three and fails when the corpus has moved without a re-seed.

Known gap, stated rather than papered over: the hash covers the corpus *sources*,
not the chunking parameters or the embedding model version. Change ``chunking.py``
or the ``bge-m3`` weights and the fixture is stale without the guard saying so —
what the guard catches is the case that actually happens, a corpus edit.

Usage::

    uv run python scripts/seed_fixture.py            # write fixtures/e2e/manifest.json
    uv run python scripts/seed_fixture.py --check    # exit 1 if the manifest is stale
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
_CORPUS_DIR = _ROOT / "src" / "tessera" / "corpus" / "data"
_FIXTURE_DIR = _ROOT / "fixtures" / "e2e"
_DUMP = _FIXTURE_DIR / "pgvector-seed.sql.gz"
_MANIFEST = _FIXTURE_DIR / "manifest.json"

_VECTOR_DDL = re.compile(r"embedding\s+\S*vector\((\d+)\)")
_COPY_START = re.compile(r"^COPY\s+(\S+)\s+\(.*\)\s+FROM\s+stdin;\s*$")


def corpus_sha256() -> str:
    """Hash of every corpus source file, order-independent of the filesystem.

    The name is hashed with the bytes: renaming a corpus file is a corpus change
    even when its content is untouched.
    """
    digest = hashlib.sha256()
    for path in sorted(_CORPUS_DIR.glob("*.json")):
        digest.update(path.name.encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def read_dump_facts(dump: Path) -> dict[str, object]:
    """Count the seeded rows and read the vector width straight out of the dump."""
    rows: dict[str, int] = {}
    dimension: int | None = None
    current: str | None = None
    with gzip.open(dump, "rt", encoding="utf-8") as handle:
        for line in handle:
            if current is not None:
                if line.startswith("\\."):
                    current = None
                else:
                    rows[current] = rows.get(current, 0) + 1
                continue
            match = _COPY_START.match(line)
            if match:
                current = match.group(1)
                rows.setdefault(current, 0)
                continue
            if dimension is None:
                vector = _VECTOR_DDL.search(line)
                if vector:
                    dimension = int(vector.group(1))
    if dimension is None:
        msg = f"{dump.name}: no `embedding vector(N)` column — this is not a pgvector seed"
        raise SystemExit(msg)
    return {"embedding_dimension": dimension, "rows": rows}


def build_manifest() -> dict[str, object]:
    """The manifest as the dump and the corpus sources jointly determine it."""
    if not _DUMP.exists():
        msg = f"{_DUMP} is missing — run `make seed-fixture` first"
        raise SystemExit(msg)
    facts = read_dump_facts(_DUMP)
    return {
        "_comment": (
            "Generated by `make seed-fixture` — never edit by hand. "
            "`corpus_sha256` is the staleness guard: it must match the corpus sources."
        ),
        "corpus_sha256": corpus_sha256(),
        "corpus_files": sorted(p.name for p in _CORPUS_DIR.glob("*.json")),
        "dump": _DUMP.name,
        "dump_sha256": hashlib.sha256(_DUMP.read_bytes()).hexdigest(),
        **facts,
    }


def main() -> int:
    """Write the manifest, or verify it, and say which."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed manifest instead of rewriting it",
    )
    args = parser.parse_args()

    manifest = build_manifest()
    if args.check:
        if not _MANIFEST.exists():
            sys.stderr.write(f"{_MANIFEST} is missing — run `make seed-fixture`\n")
            return 1
        committed = json.loads(_MANIFEST.read_text(encoding="utf-8"))
        if committed != manifest:
            sys.stderr.write(
                "the seed fixture is stale: the corpus sources or the dump have moved "
                "since it was generated — run `make seed-fixture`\n"
            )
            return 1
        sys.stdout.write("seed fixture manifest is current\n")
        return 0

    _MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    rows = manifest["rows"]
    sys.stdout.write(f"wrote {_MANIFEST.relative_to(_ROOT)} — rows={rows}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
