"""Enum codegen from the AgentSpec capabilities (ADR 0018 §C).

The per-agent intent vocabulary is **generated** from the manifest, never
hand-written platform unions — the O(agents) enum smell made unrepresentable
(ADR 0018 §2). The render functions are pure and deterministic (capability ids,
sorted); :mod:`scripts.generate_agent_enums` writes their output to committed
files, and ``tests/unit/test_agent_enum_codegen.py`` re-renders and diffs to keep
the committed files honest (the generate-and-diff CI gate).

Reads the manifest through the one boundary-allowed seam (``tessera.agent.registry``,
ADR 0017 §1), exactly like :mod:`tessera.observability.agentspec_projection`.
"""

from __future__ import annotations

from tessera.agent.registry import get_agent

_BACKEND_REL = "src/tessera/agent/generated/{module}.py"
_FRONTEND_REL = "webapp/frontend/components/recouvrement/{stem}.generated.ts"


def capability_ids(agent_id: str) -> tuple[str, ...]:
    """The agent's declared capability ids, sorted — the per-agent intent vocabulary."""
    spec = get_agent(agent_id).observability
    if spec is None:
        return ()
    return tuple(sorted(cap.id for cap in spec.capabilities))


def artifact_type_capabilities(agent_id: str) -> tuple[tuple[str, str], ...]:
    """``(artifact_type, capability_id)`` pairs from the manifest's ``output_artifacts``.

    The second half of the per-agent vocabulary (ADR 0018 §C): a capability declares what it
    produces, so the artifact type an agent can emit is a *derived* fact, never a union the
    frontend re-types by hand. Sorted, and an artifact type declared by two capabilities keeps
    the first by sort order — a genuine ambiguity we surface as a stable choice rather than a
    random one. (Today there is none.)
    """
    spec = get_agent(agent_id).observability
    if spec is None:
        return ()
    pairs: dict[str, str] = {}
    for capability in sorted(spec.capabilities, key=lambda cap: cap.id):
        for artifact_type in capability.output_artifacts:
            pairs.setdefault(artifact_type, capability.id)
    return tuple(sorted(pairs.items()))


def _pascal(agent_id: str) -> str:
    return "".join(part.capitalize() for part in agent_id.split("_"))


def render_backend_enums(agent_id: str) -> str:
    """Render the generated backend ``Literal`` module for ``agent_id`` (ADR 0018 §C)."""
    ids = capability_ids(agent_id)
    pascal = _pascal(agent_id)
    const = f"{agent_id.upper()}_CAPABILITY_IDS"
    members = "".join(f'    "{cid}",\n' for cid in ids)
    return (
        "# @generated by scripts/generate_agent_enums.py from "
        "src/tessera/agent/agents.yaml — DO NOT EDIT.\n"
        "# Regenerate: uv run python scripts/generate_agent_enums.py\n"
        f'"""Generated per-agent intent enum for `{agent_id}` (ADR 0018 §C).\n\n'
        "Derived from the AgentSpec ``capabilities`` block — the intent vocabulary a\n"
        "typed action or a routed free message resolves to. Hand edits are overwritten.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        "from typing import Literal\n\n"
        f"#: The declared capability ids for `{agent_id}`, sorted.\n"
        f"{const}: tuple[str, ...] = (\n{members})\n\n"
        f"{pascal}Intent = Literal[\n{members}]\n"
    )


def render_frontend_enums(agent_id: str) -> str:
    """Render the generated frontend union module for ``agent_id`` (ADR 0018 §C)."""
    ids = capability_ids(agent_id)
    pascal = _pascal(agent_id)
    const = f"{agent_id.upper()}_INTENTS"
    members = "".join(f'  "{cid}",\n' for cid in ids)
    pairs = artifact_type_capabilities(agent_id)
    artifact_const = f"{agent_id.upper()}_ARTIFACT_CAPABILITY"
    # Emit exactly what `biome format` would print (unquoted keys, one-line `satisfies`), so the
    # generate-and-diff gate and the formatter never disagree about the committed file.
    entries = "".join(f'  {artifact}: "{capability}",\n' for artifact, capability in pairs)
    return (
        "// @generated by scripts/generate_agent_enums.py from "
        "src/tessera/agent/agents.yaml — DO NOT EDIT.\n"
        "// Regenerate: uv run python scripts/generate_agent_enums.py\n"
        f"export const {const} = [\n{members}] as const;\n\n"
        f"export type {pascal}Intent = (typeof {const})[number];\n\n"
        "/** Which capability declares each artifact type (manifest `output_artifacts`). */\n"
        f"export const {artifact_const} = {{\n{entries}}} as const satisfies Record<"
        f"string, {pascal}Intent>;\n\n"
        f"export type {pascal}ArtifactType = keyof typeof {artifact_const};\n"
    )


def backend_path(agent_id: str) -> str:
    """Repo-relative path of the generated backend module for ``agent_id``."""
    return _BACKEND_REL.format(module=f"{agent_id}_enums")


def frontend_path(agent_id: str) -> str:
    """Repo-relative path of the generated frontend module for ``agent_id``."""
    return _FRONTEND_REL.format(stem=f"{agent_id}-enums")
